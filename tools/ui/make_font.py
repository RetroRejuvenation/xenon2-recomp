"""Convert the vendored Unscii .hex fonts into runtime/ui/font_data.inc, the launcher UI's bitmap font.

    python3 tools/ui/make_font.py            write runtime/ui/font_data.inc
    python3 tools/ui/make_font.py --check    fail if the committed file is not what this script produces

Input: vendor/unscii/unscii-16.hex (8x16) and unscii-8.hex (8x8), public domain (vendor/unscii/LICENSE-unscii.txt).
Only the code points the UI draws are kept: ASCII, Latin-1, Latin Extended-A, general punctuation the UI uses, arrows,
box drawing, block elements, geometric shapes and a few symbols. Entries that are not 8 pixels wide are skipped.
The output is deterministic (sorted by code point) so --check is exact.
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, "runtime", "ui", "font_data.inc")

WANTED = (
    list(range(0x20, 0x7F))
    + list(range(0xA0, 0x100))
    + list(range(0x100, 0x180))
    + [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC, 0x2122, 0x2713, 0x2605, 0x2606, 0x266A, 0x266B]
    + list(range(0x2190, 0x2196))
    + [c for c in range(0x2500, 0x2600) if c not in (0x25FD, 0x25FE)]  # not in unscii-16
)


def load(path, rows):
    glyphs = {}
    with open(path, "r", encoding="ascii") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            cp, data = line.split(":")
            if len(data) != rows * 2:  # wide (16-pixel) glyph
                continue
            glyphs[int(cp, 16)] = bytes.fromhex(data)
    return glyphs


def render():
    out = []
    out.append("// Generated by tools/ui/make_font.py from vendor/unscii/unscii-{8,16}.hex (Unscii 2.1 by Viznut). Public domain: vendor/unscii/LICENSE-unscii.txt.")
    out.append("// Do not edit. Each row is one byte, most significant bit = leftmost pixel.")
    for name, rows, fname in (("kGlyphs16", 16, "unscii-16.hex"), ("kGlyphs8", 8, "unscii-8.hex")):
        src = load(os.path.join(ROOT, "vendor", "unscii", fname), rows)
        missing = [c for c in WANTED if c not in src]
        if missing:
            sys.stderr.write("%s: %d wanted code points missing: %s\n" % (fname, len(missing), " ".join("U+%04X" % c for c in missing[:20])))
        cps = sorted(c for c in set(WANTED) if c in src)
        out.append("static const GlyphRow%d %s[] = {" % (rows, name))
        for c in cps:
            out.append("  {0x%04X, {%s}}," % (c, ",".join("0x%02X" % b for b in src[c])))
        out.append("};")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        with open(OUT, "r", encoding="ascii") as f:  # universal newlines: a Windows checkout may have CRLF
            if f.read() != text:
                sys.stderr.write("runtime/ui/font_data.inc is out of date: run tools/ui/make_font.py\n")
                return 1
        return 0
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
