GLYPH_W = 5
GLYPH_H = 7
ADVANCE = 6  # 5 pixels and one of spacing


def _rows(ch):
    g = _GLYPH_ROWS.get(ch.upper(), _GLYPH_ROWS["?"])
    return g.split("|")


def text_size(text, scale=1):
    """Width and height in pixels of `text` drawn with `draw_text` (a single line)."""
    if not text:
        return 0, GLYPH_H * scale
    return (len(text) * ADVANCE - 1) * scale, GLYPH_H * scale


def draw_text(img, x, y, text, rgba=(255, 255, 255, 255), scale=1):
    """Draw one line of `text` with its top-left corner at x, y into an `pack_lib.Image` (clipped, opaque pixels)."""
    px = bytes(rgba)
    for i, ch in enumerate(text):
        gx = x + i * ADVANCE * scale
        for ry, row in enumerate(_rows(ch)):
            for rx, c in enumerate(row):
                if c == "#":
                    for sy in range(scale):
                        for sx in range(scale):
                            xx, yy = gx + rx * scale + sx, y + ry * scale + sy
                            if 0 <= xx < img.w and 0 <= yy < img.h:
                                o = (yy * img.w + xx) * 4
                                img.data[o:o + 4] = px
