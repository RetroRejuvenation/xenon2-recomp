"""Generate the CDTV replay scripts tests/replays/cdtv/*.txt (input scripts for x2recomp --input-script).

The CDTV release has its own front end (joypad-mode page, title pages, a 1/2-player menu), so the disk build's scripts do not
apply to it. Timings were measured against the interpreter runtime (docs/re-notes/cdtv-boot.md): the first fire confirms the
joypad mode at about frame 200; further presses every 150 frames walk through the title pages and the menu; LEVEL1 is
loaded at about frame 2105 and the ship is controllable from about frame 2300.

    python3 tools/trace/make_cdtv_replays.py [--out tests/replays/cdtv]

Game variables used by the one coverage poke (docs/re-notes/cdtv-c0.md section 3): $CA6.w special weapons carried (hunk $8A6).
Second button: the `B` letter of `joy` lines (POTGOR bit 14), held for at least 20 frames because the game samples it once
every 20 vertical blanks.
"""
import argparse
import os

HEAD = "# {name}: {title}\n# generated by tools/trace/make_cdtv_replays.py\n"
MENUS = "200 fire 6 every 150 until 2000\n"  # joypad mode, title pages, menu: level 1 starts at about frame 2105


def scripts():
    s = {}
    s["attract"] = ("the joypad-mode page and the title pages (no input after the first fire)", "frames 1500\n200 fire 6\n")
    s["menus"] = ("fire through every menu page into level 1 (no gameplay input)", "frames 2500\n" + MENUS)
    s["level1_play"] = (
        "menus, then level 1 with the ship sweeping left and right and firing",
        "frames 6000\n" + MENUS +
        "2300 fire 3 every 5 until 5900\n"
        "2300 joy L 40 every 160 until 5800\n"
        "2380 joy R 40 every 160 until 5800\n"
        "2340 joy U 20 every 320 until 5700\n"
        "2500 joy D 20 every 320 until 5700\n")
    s["level1_special"] = (
        "level 1 with three special weapons poked in (COVERAGE) and the second button pressed",
        "frames 3600\n" + MENUS +
        "2300 fire 3 every 5 until 3500\n"
        "2400 poke 0xCA6 3\n"
        "2420 joy B 30\n"
        "2800 joy B 30\n"
        "3200 joy B 30\n")
    return s


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "..", "tests", "replays", "cdtv"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    for name, (title, body) in scripts().items():
        with open(os.path.join(a.out, name + ".txt"), "w", newline="\n") as f:
            f.write(HEAD.format(name=name, title=title) + body)
        print("wrote", name)


if __name__ == "__main__":
    main()
