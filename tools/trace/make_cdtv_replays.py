MENUS = "200 fire 6 every 150 until 2000\n"  # joypad mode, title pages, language page, SELECT menu: level 1 loads at ~2105


def front_end(s, players=1):
    """Joypad-mode page, title, guide pages, SELECT menu -> N PLAYER GAME. A fire every 40 frames walks the pages (measured: the
    menu text finishes building at ~1450 and then takes input, so 2 PLAYER GAME is one `down` at 1490 before the starting fire
    at 1520); level 1 loads at ~1545 and waits at GET READY for a fire; the ship is controllable from ~1760."""
    s.note(f"joypad mode, title pages, guide pages, SELECT menu -> {players} PLAYER GAME (level 1 loads at ~1545)")
    s.ev("fire 6 every 40 until 1360", 200)
    if players == 2:
        s.ev("joy D 4", 1490)
    s.ev("fire 6", 1520)
    s.ev("fire 3 every 5 until 1760", 1700)
    return s.at(1780)


def play(s, n, moves="LRLRUDUD", seg=40):
    """Real play for n frames: fire tapped every 4 frames while sweeping the ship around."""
    if n < seg:
        return s.wait(max(0, n))
    s.note(f"play {n} frames: autofire taps while moving {moves}")
    end = s.t + n
    s.ev(f"joy F 2 every 4 until {end - 4}")
    i = 0
    while s.t + seg <= end:
        s.ev(f"joy {moves[i % len(moves)]} {seg - 6}")
        s.wait(seg)
        i += 1
    return s.at(end)


def invincible(s, frames):
    s.note(f"COVERAGE POKE: energy $CCC=$27 and ships $CD0=3 every frame for {frames} frames")
    s.poke(ENERGY, 0x27, frames=frames).poke(SHIPS, 3, frames=frames)
    return s


def flood_to(s, pos):
    """Jump the scroll position in one step without moving the event cursors: the level's event scan then fires every event of
    the skipped stretch at once (many enemy types alive together; it can exhaust the object pool, so only where it tested
    healthy)."""
    s.note(f"COVERAGE POKE: jump the scroll position ($CD6/$CF0, $CD4 = 2.5x, clamp $CEE) to ${pos:X}; the skipped events all fire")
    s.poke(POS, pos).poke(POS2, pos).poke(POSX, pos * 5 // 2)
    return s.poke(CLAMP, max(0, pos - 0x40))


def scroll_to(s, pos):
    """Jump the level scroll position and the event cursors together: the skipped stretch's events are dropped."""
    s.note(f"COVERAGE POKE: jump the scroll position ($CD6/$CF0/$CD8/$CDA, $CD4 = 2.5x) to ${pos:X}")
    for a in (POS, POS2, CUR1, CUR2):
        s.poke(a, pos)
    return s.poke(POSX, pos * 5 // 2)


def fast_forward(s, start, stop, step=0x40, every=50, moves="LRLRUDUD"):
    """Advance the scroll position by `step` every `every` frames (the natural speed is ~0.26 rows per frame, so the default is
    ~5x) while playing. Only the position moves ($CD6/$CF0/$CD4): the event scan still fires every event passed, a few at a
    time. The lower scroll clamp $CEE is lowered just below each new position (a position under the clamp gives the scroll
    update a huge delta, which ends in a stray blit over the level overlay; see tests/replays/README.md)."""
    s.note(f"COVERAGE POKE: fast-forward the scroll position ${start:X} -> ${stop:X}, -${step:X} every {every} frames")
    t0 = s.t
    n = (start - stop) // step + 1
    play(s, n * every, moves)
    for i in range(n):
        p = start - i * step
        s.ev(f"poke ${POS:X} ${p:X}.w", t0 + i * every)
        s.ev(f"poke ${POS2:X} ${p:X}.w", t0 + i * every)
        s.ev(f"poke ${POSX:X} ${p * 5 // 2:X}.w", t0 + i * every)
        s.ev(f"poke ${CLAMP:X} ${max(0, p - step):X}.w", t0 + i * every)
    s.pokes = True
    return s


def goto_level(s, level):
    """From a running level: set the level counter to level-1 and raise the level-complete flag: the main loop's own
    end-of-level path loads the requested level (LEVELn and SOUNDSnn are opened)."""
    s.note(f"COVERAGE POKE: $E0A={level - 1}, $A0D=$FF -> the game's end-of-level path loads level {level}")
    s.poke(LEVEL, level - 1).poke(DONE, 0xFF, "b")
    s.ev("fire 5 every 50 until %d" % (s.t + 450))
    return s.wait(450)


def shop_request(s):
    s.note("COVERAGE POKE: $A72=$FF -> shop request (the main loop loads the shop; SOUNDS00 and a SPEECHnn are opened)")
    return s.poke(SHOPREQ, 0xFF, "b")


def shop(s, cells=4, step=18):
    """Shop: the same input loop as the disk build's, but every shopkeeper phrase is a speech sample (a SPEECHnn file loaded from
    the disc), and input is only taken between phrases, so one purchase takes about 200 frames (the disk build's takes 90). It is
    ready ~450 frames after the request. Cursor: $4F8 column 0-4, $4FA row 0-4, starting at (0,0); row 4 is the bottom bar where
    column 0 is EXIT and any other column the SELL/BUY button. The shop opens in the SELL phase; EXIT there moves on to the BUY
    phase, where fire on a cell selects the item and a second fire on the same cell buys it; EXIT in the BUY phase leaves."""
    if cells == 0:
        s.note("shop: leave at once (EXIT twice: SELL phase, then BUY phase)")
        s.poke(SHOP_COL, 0).poke(SHOP_ROW, 4)
        s.wait(30).fire(gap=300)
        s.poke(SHOP_COL, 0).poke(SHOP_ROW, 4)
        return s.wait(30).fire(gap=step)
    s.note("shop SELL phase: move to the SELL button, fire (nothing to sell), then EXIT")
    s.joy("D", gap=step).joy("D", gap=step).joy("D", gap=step).joy("D", gap=step).joy("R", gap=step)
    s.fire(gap=150)
    s.note("COVERAGE POKE (UI only): cursor on EXIT ($4F8=0, $4FA=4) in case a move was dropped")
    s.poke(SHOP_COL, 0).poke(SHOP_ROW, 4)
    s.wait(40).fire(gap=300)
    s.note(f"shop BUY phase: from (0,0) buy over {cells} cells (snake; only some cells have stock), a fire every 40 frames on each (one purchase per ~200 frames)")
    row = col = 0
    for i in range(cells):
        # a fire every 40 frames for 240 frames: one purchase happens when the shopkeeper's speech lets go of the input
        s.ev(f"fire 3 every 40 until {s.t + 240}")
        s.wait(250)
        if i + 1 == cells:
            break
        if (row % 2 == 0 and col < 4) or (row % 2 == 1 and col > 0):
            col += 1 if row % 2 == 0 else -1
            s.joy("R" if row % 2 == 0 else "L", gap=step + 12)
        else:
            row += 1
            s.joy("D", gap=step + 12)
    s.note("shop: down to the bottom bar, EXIT")
    for _ in range(4 - row):
        s.joy("D", gap=step)
    if col != 0:
        s.joy("L", gap=step)
    s.note("COVERAGE POKE (UI only): cursor on EXIT in case a purchase dialog swallowed a move, then fire")
    s.wait(30).poke(SHOP_COL, 0).poke(SHOP_ROW, 4)
    return s.wait(30).fire(gap=step)


def shop_leave(s, tries=4, gap=60):
    """Leave the shop without buying: cursor on EXIT and fire, `tries` times `gap` frames apart (EXIT in the SELL phase moves on
    to the BUY phase, EXIT there leaves; spare presses after leaving only fire a shot)."""
    s.note(f"shop: leave without buying (cursor on EXIT $4F8=0/$4FA=4 and fire, {tries}x)")
    for _ in range(tries):
        s.poke(SHOP_COL, 0).poke(SHOP_ROW, 4)
        s.wait(10).fire(gap=gap - 10)
    return s


def aim(s, right, left=80):
    s.note(f"aim: left {left} frames, then right {right} frames")
    s.ev(f"joy L {left}")
    s.wait(left)
    s.ev(f"joy R {right}")
    return s.wait(right)


def autofire(s, n):
    s.note(f"hold position, autofire for {n} frames")
    s.ev(f"joy F 2 every 4 until {s.t + n - 4}")
    return s.wait(n)


