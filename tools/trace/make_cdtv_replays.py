"""Generate the CDTV replay scripts tests/replays/cdtv/*.txt (input scripts for x2recomp --input-script).

The CDTV release has its own front end (joypad-mode page, title pages, a language page that reuses the shop screen, a
1/2-player menu), so the disk build's scripts do not apply to it, but the engine is the disk build's (81 % shared) and so are
the shop and the level logic. This generator follows tools/trace/make_replays.py with the CDTV addresses.

    python3 tools/trace/make_cdtv_replays.py [--out tests/replays/cdtv] [NAME...]

Timings were measured against the interpreter runtime (docs/re-notes/cdtv-boot.md): the first fire confirms the joypad mode at
about frame 200; further presses every 150 frames walk through the title pages and the language page; the SELECT menu is up from
about frame 1950; the fire at frame 2000 starts the game; LEVEL1 is loaded at 2105 and the ship is controllable from about 2300.

Addresses. Hunk addresses of docs/re-notes/cdtv-c0.md section 3 + $400 are absolute addresses. The engine's variable block is the
disk build's moved by exactly +6 (absolute), checked against RAM dumps of both builds (docs/re-notes/cdtv-replays.md):

  $E0A.w level 1-5        $A0D.b level-complete flag   $A72.b shop request     $CD6/$CF0/$CD4.w scroll position ($CD4 = 2.5x)
  $CEE.w lower scroll clamp  $CD8/$CDA.w event cursors  $CCC.w energy (max $27) $CD0.w ships  $CF6.w credits
  $C98.l score  $CA0.l cash  $4F8/$4FA.w shop cursor column/row   $B52.l head of the hittable-object list
  $3D24E.b ending flag (set by the game when the level-5 shop is requested late in the level)
  $CA6.w special weapons carried (the second button fires them)
Boss objects are found by their hit handler (+$A) on the list $B52 (docs/re-notes/cdtv-replays.md has the handler table).

Second button: the `B` letter of `joy` lines (POTGOR bit 14), held for at least 20 frames because the game samples it once every
20 vertical blanks.
"""
import argparse
import os
import sys

KEY_P, KEY_ESC, KEY_SPACE = 0x19, 0x45, 0x40

# CDTV absolute addresses (engine variable block = disk build + 6)
LEVEL, DONE, SHOPREQ = 0xE0A, 0xA0D, 0xA72
POS, POS2, POSX, CLAMP, CUR1, CUR2 = 0xCD6, 0xCF0, 0xCD4, 0xCEE, 0xCD8, 0xCDA
ENERGY, SHIPS, CREDITS, SCORE, CASH = 0xCCC, 0xCD0, 0xCF6, 0xC98, 0xCA0
SHOP_COL, SHOP_ROW = 0x4F8, 0x4FA
SPECIALS = 0xCA6
LOOP = 0xE08


class Script:
    def __init__(self, name, title):
        self.name = name
        self.lines = [f"# {name}: {title}", "# generated by tools/trace/make_cdtv_replays.py"]
        self.t = 0
        self.pokes = False

    def at(self, t):
        self.t = t
        return self

    def wait(self, n):
        self.t += n
        return self

    def note(self, text):
        self.lines.append(f"# {text}")
        return self

    def ev(self, text, t=None):
        self.lines.append(f"{self.t if t is None else t} {text}")
        return self

    def fire(self, hold=3, gap=20):
        self.ev(f"fire {hold}")
        return self.wait(gap)

    def joy(self, dirs, hold=3, gap=20):
        self.ev(f"joy {dirs} {hold}")
        return self.wait(gap)

    def key(self, code, gap=20):
        self.ev(f"key {code:02x}")
        return self.wait(gap)

    def poke(self, addr, val, size="w", frames=1):
        self.pokes = True
        self.ev(f"poke ${addr:X} ${val:X}.{size}" + (f" {frames}" if frames != 1 else ""))
        return self

    def pokeobj(self, handler, offset, val, size="w", frames=1):
        self.pokes = True
        self.ev(f"pokeobj ${handler:X} ${offset:X} ${val:X}.{size}" + (f" {frames}" if frames != 1 else ""))
        return self

    def text(self):
        hdr = "# COVERAGE POKES ARE USED: game state is altered, not a faithful playthrough" if self.pokes else \
              "# no pokes: plain input only"
        return "\n".join(self.lines[:2] + [hdr] + self.lines[2:] + [f"frames {self.t}"]) + "\n"


