class Raw:
    """A script kept byte-identical to the one the committed hash manifest was recorded with (C3)."""
    pokes = False

    def __init__(self, name, title, body, pokes=False):
        self.name, self.title, self.body, self.pokes = name, title, body, pokes
        self.t = int(body.split("frames ")[1].split()[0])

    def text(self):
        return f"# {self.name}: {self.title}\n# generated by tools/trace/make_cdtv_replays.py\n" + self.body


