# --- Hatari-format copy ----------------------------------------------------------------------------------

JOY_BITS = {"U": "UP", "D": "DOWN", "L": "LEFT", "R": "RIGHT", "F": "FIRE"}


def to_hatari(text, base=0, shifts=(), anchors=(), shots=(), extend=0, rams=()):
    """Convert a script to the Hatari harness's lines (tools/compare/hatari-harness): joy/fire/key events become edge lines
    `<vbl> JOY1_<DIR> 0|1` / `<vbl> KEY<hex> 0|1`, pokes become `<vbl> POKE <addr> <value> <size>` and
    `<vbl> POKEOBJ <handler> <offset> <value> <size>` (patch 0002; a poke held N frames is one line per VBL).

    Events before the first anchor land at Hatari VBL t + base + the extra of the last (from, extra) pair in `shifts` with from <= t
    (Hatari counts VBLs from emulator start, EmuTOS boots for ~436 first, and its floppy runs at real speed, so the front end and the
    first level load take far longer). `anchors` = [(script frame, level)]: from each anchor on, events are written as `+<delta>`
    lines under an `ANCHOR <level>` line, which the harness runs <delta> VBLs after the first scroll movement once that level is up:
    the inputs are timed from the game's own event, not from the VBL count (the load times vary from run to run). `shots` are script
    frames at which a screenshot is wanted after the first anchor (`+<delta> SHOT`). `rams` are script frames at which the harness dumps the ST's RAM (`+<delta> RAM`). `extend` lengthens every fire chain that runs before
    the first anchor by that many VBLs (the GET READY fires after a level load that Hatari takes longer over)."""
    anchors = sorted(anchors)

    def at(t):
        extra = 0
        for frm, ex in shifts:
            if t >= frm:
                extra = ex
        return t + base + extra

    def group(t):
        k = None
        for i, (ta, _) in enumerate(anchors):
            if t >= ta:
                k = i
        return k

    def num(s):
        s = s.lstrip("$")
        return int(s[2:], 16) if s.lower().startswith("0x") else int(s, 16)

    def val(s):
        size = {"b": 1, "w": 2, "l": 4}[s.split(".")[1]] if "." in s else 2
        return num(s.split(".")[0]), size

    items = []   # (group or None, time key, order, text)

    def emit(t, body, order=1):
        k = group(t)
        items.append((k, at(t) if k is None else t - anchors[k][0], order, body))

    for line in text.splitlines():
        line = line.split("#")[0].strip()
        m = re.match(r"(\d+) (joy|fire|key|poke|pokeobj) (.*)", line)
        if not m:
            continue
        t, kind, rest = int(m.group(1)), m.group(2), m.group(3).split()
        if kind in ("poke", "pokeobj"):
            n = int(rest[-1]) if len(rest) == (3 if kind == "poke" else 4) else 1
            if kind == "poke":
                v, size = val(rest[1])
                body = f"POKE {num(rest[0]):X} {v:X} {size}"
            else:
                v, size = val(rest[2])
                body = f"POKEOBJ {num(rest[0]):X} {num(rest[1]):X} {v:X} {size}"
            for i in range(n):
                emit(t + i, body)
            continue
        every = until = None
        if "every" in rest:
            i = rest.index("every")
            every, until = int(rest[i + 1]), int(rest[i + 3])
            rest = rest[:i]
        if kind == "fire":
            names, hold = ["FIRE"], int(rest[0])
        elif kind == "joy":
            names, hold = [JOY_BITS[c] for c in rest[0]], int(rest[1])
        else:
            names, hold = ["KEY%02X" % int(rest[0], 16)], int(rest[1]) if len(rest) > 1 else 6
        times = [t] if every is None else list(range(t, until + 1, every))
        for tt in times:
            for n in names:
                pre = "" if n.startswith("KEY") else "JOY1_"
                emit(tt, f"{pre}{n} 1", 1)
                emit(tt + hold, f"{pre}{n} 0", 0)
        if every is not None and group(until) is None and extend:
            for k in range(every, extend + 1, every):
                for n in names:
                    pre = "" if n.startswith("KEY") else "JOY1_"
                    items.append((None, at(until) + k, 1, f"{pre}{n} 1"))
                    items.append((None, at(until) + k + hold, 0, f"{pre}{n} 0"))
        if every is not None and group(until) is None:
            # a chain that ends just before a shift (the front end's GET READY fires, before the slower Hatari load) goes on through it
            for frm, ex in shifts:
                if until < frm <= until + 60:
                    last = at(until)
                    for k in range(every, at(frm) - at(frm - 1), every):
                        for n in names:
                            pre = "" if n.startswith("KEY") else "JOY1_"
                            items.append((None, last + k, 1, f"{pre}{n} 1"))
                            items.append((None, last + k + hold, 0, f"{pre}{n} 0"))
    for f in shots:
        k = group(f)
        if k is not None:
            items.append((k, f - anchors[k][0], 2, "SHOT"))
    for f in rams:
        k = group(f)
        if k is not None:
            items.append((k, f - anchors[k][0], 2, "RAM"))
    out = []
    absolute = sorted((i for i in items if i[0] is None), key=lambda x: (x[1], x[2]))
    out += [f"{i[1]} {i[3]}" for i in absolute]
    for k, (ta, lvl) in enumerate(anchors):
        out.append(f"ANCHOR {lvl}")
        out += [f"+{i[1]} {i[3]}" for i in sorted((i for i in items if i[0] == k), key=lambda x: (x[1], x[2]))]
    return "\n".join(out) + "\n"


# --- manifests -------------------------------------------------------------------------------------------

def total_frames(text):
    for line in text.splitlines():
        if line.startswith("frames "):
            return int(line.split()[1])
    raise ValueError("no frames line")


def record(exe, disk, script_path):
    """Run the script and write the manifest: the frame hash and the cumulative audio hash every 500 frames and at the last frame."""
    n = total_frames(open(script_path).read())
    frames = list(range(500, n, 500)) + [n - 1]
    cmd = [exe, "--game", "st", "--headless", "--st-disk", disk, "--st-fdc-speed", "8", "--report-every", "0",
           "--input-script", script_path, "--audio-hash"]
    for f in frames:
        cmd += ["--hash-at", str(f)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"{script_path}: x2recomp exited with {r.returncode}\n{r.stdout}{r.stderr}")
    if not re.search(r"\b0 unmapped accesses", r.stdout):
        raise SystemExit(f"{script_path}: unmapped accesses\n{r.stdout}")
    got = re.findall(r"^((?:frame|audio)hash \d+ [0-9a-f]+)$", r.stdout, re.M)
    if len(got) != 2 * len(frames):
        raise SystemExit(f"{script_path}: expected {2 * len(frames)} hashes, got {len(got)}\n{r.stdout}")
    return "\n".join(got) + "\n"


def main():
    ap = argparse.ArgumentParser()
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
    ap.add_argument("--out", default=os.path.join(root, "tests", "replays", "st"))
    ap.add_argument("--record", action="store_true", help="write NAME.hashes next to the scripts instead of the scripts")
    ap.add_argument("--exe", default=os.path.join(root, "build", "x2recomp"))
    ap.add_argument("--disk")
    ap.add_argument("--hatari", action="store_true", help="print/write the Hatari-format copy of the named scripts")
    ap.add_argument("--out-hatari", default=None)
    ap.add_argument("--base", type=int, default=436, help="--hatari: Hatari VBLs of the EmuTOS boot")
    ap.add_argument("--shift", action="append", default=[], metavar="FROM:EXTRA", help="--hatari: from script frame FROM add EXTRA VBLs")
    ap.add_argument("names", nargs="*")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    names = a.names or list(REPLAYS)
    for name in names:
        path = os.path.join(a.out, name + ".txt")
        if a.record:
            if not a.disk:
                ap.error("--record needs --disk")
            with open(os.path.join(a.out, name + ".hashes"), "w", newline="\n") as f:
                f.write(record(a.exe, a.disk, path))
            print(f"{name}: recorded", file=sys.stderr)
        elif a.hatari:
            text = to_hatari(open(path).read(), a.base, sorted(tuple(int(x) for x in s.split(':')) for s in a.shift))
            if a.out_hatari:
                os.makedirs(a.out_hatari, exist_ok=True)
                with open(os.path.join(a.out_hatari, name + ".hatari.txt"), "w", newline="\n") as f:
                    f.write(text)
            else:
                sys.stdout.write(text)
        else:
            s = REPLAYS[name]()
            with open(path, "w", newline="\n") as f:
                f.write(s.text())
            print(f"{name}: {s.t} frames{' (pokes)' if s.pokes else ''}", file=sys.stderr)


if __name__ == "__main__":
    main()
