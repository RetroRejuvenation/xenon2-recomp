import subprocess
import sys

KEY_P, KEY_ESC, KEY_SPACE = 0x19, 0x01, 0x39  # ST scancodes

# disk-build engine variables at the ST's addresses
LEVEL, LOOP, DONE, SHOPREQ = 0xE04, 0xE02, 0xA07, 0xA6C
POS, POS2, POSX, CLAMP, CUR1, CUR2 = 0xCD0, 0xCEA, 0xCCE, 0xCE8, 0xCD2, 0xCD4
ENERGY, SHIPS, CREDITS, SCORE, CASH = 0xCC6, 0xCCA, 0xCF0, 0xC92, 0xC9A
SHOP_COL, SHOP_ROW = 0x4F2, 0x4F4
GUARDS_LEFT = 0xD7A
SPECIALS = 0xCA0

# hit handlers of the boss objects (the ST's level code at $4F000; obj+$32 is the HP): see docs/re-notes/atari-st-replays.md
H_BOSS1 = 0x50396         # level 1 nautilus, HP $1E
H_SPIDER = 0x50A16        # level 2 spider, HP $4B
HANDLERS = {}


class Script:
    def __init__(self, name, title):
        self.name = name
        self.lines = [f"# {name}: {title}", "# generated by tools/trace/make_st_replays.py"]
        self.t = 0
        self.pokes = False

    def at(self, t):
        self.t = t
        return self

    def wait(self, n):
        self.t += n
        return self

    def note(self, text):
        self.lines.append(f"# {text}")
        return self

    def ev(self, text, t=None):
        self.lines.append(f"{self.t if t is None else t} {text}")
        return self

    def fire(self, hold=10, gap=40):
        self.ev(f"fire {hold}")
        return self.wait(gap)

    def joy(self, dirs, hold=12, gap=30):
        self.ev(f"joy {dirs} {hold}")
        return self.wait(gap)

    def key(self, code, hold=6, gap=30):
        self.ev(f"key {code:02x} {hold}")
        return self.wait(gap)

    def poke(self, addr, val, size="w", frames=1):
        self.pokes = True
        self.ev(f"poke ${addr:X} ${val:X}.{size}" + (f" {frames}" if frames != 1 else ""))
        return self

    def pokeobj(self, handler, offset, val, size="w", frames=1):
        self.pokes = True
        self.ev(f"pokeobj ${handler:X} ${offset:X} ${val:X}.{size}" + (f" {frames}" if frames != 1 else ""))
        return self

    def text(self):
        hdr = "# COVERAGE POKES ARE USED: game state is altered, not a faithful playthrough" if self.pokes else \
              "# no pokes: plain input only"
        return "\n".join(self.lines[:2] + [hdr] + self.lines[2:] + [f"frames {self.t}"]) + "\n"


# --- building blocks -------------------------------------------------------------------------------------

def front_end(s, players=1):
    """Title -> SELECT menu -> N PLAYER GAME -> loading level 1 -> GET READY (a fire ends it): the ship is controllable from ~2200."""
    s.note(f"title -> SELECT menu -> {players} PLAYER GAME -> loading level 1 -> GET READY (level 1 loads at ~1760)")
    s.ev("fire 6", 1400)
    if players == 2:
        s.ev("joy D 12", 1620)
    s.ev("fire 10", 1650)
    s.ev("fire 6 every 50 until 2150", 1700)
    return s.at(2200)


def play(s, n, moves="LRLRUDUD", seg=40):
    """Real play for n frames: fire tapped every 4 frames while sweeping the ship around."""
    if n < seg:
        return s.wait(max(0, n))
    s.note(f"play {n} frames: autofire taps while moving {moves}")
    end = s.t + n
    s.ev(f"joy F 2 every 4 until {end - 4}")
    i = 0
    while s.t + seg <= end:
        s.ev(f"joy {moves[i % len(moves)]} {seg - 6}")
        s.wait(seg)
        i += 1
    return s.at(end)


def invincible(s, frames):
    s.note(f"COVERAGE POKE: energy $CC6=$27 and ships $CCA=3 every frame for {frames} frames")
    s.poke(ENERGY, 0x27, frames=frames).poke(SHIPS, 3, frames=frames)
    return s


def flood_to(s, pos):
    """Jump the scroll position in one step without moving the event cursors: the level's event scan then fires every event of the
    skipped stretch at once (many enemy types alive together; it can exhaust the object pool, so only where it tested healthy)."""
    s.note(f"COVERAGE POKE: jump the scroll position ($CD0/$CEA, clamp $CE8) to ${pos:X}; the skipped events all fire")
    s.poke(POS, pos).poke(POS2, pos)
    return s.poke(CLAMP, max(0, pos - 0x40))


def scroll_to(s, pos):
    """Jump the scroll position and the event cursors together: the skipped stretch's events are dropped."""
    s.note(f"COVERAGE POKE: jump the scroll position ($CD0/$CEA/$CD2/$CD4) to ${pos:X}")
    for a in (POS, POS2, CUR1, CUR2):
        s.poke(a, pos)
    return s


def fast_forward(s, start, stop, step=8, every=6, moves="LRLR"):
    """Advance the scroll position by `step` every `every` frames (the natural speed is ~0.28/frame, so the default is ~4.5x) while
    playing. The event scan still fires every event passed, a few at a time. The lower scroll clamp $CE8 is lowered just below each
    new position (a position under the clamp gives the scroll update a huge delta).

    The ship is kept at the top of the screen (up held, sweeping left and right): the ship code at $6AFC adds the ship's previous
    y to the distance the scroll position has just moved, and when the sum passes $B0 it subtracts the excess from the scroll speed
    ($CDA), so a ship low on the screen turns every `step` jump into a negative speed that flies the position back (the sub-tile row
    $CD6 then leaves 0-15 and the tile routine at $1E90 loops over unmapped memory). Up at the top the sum stays below $B0."""
    s.note(f"COVERAGE POKE: fast-forward the scroll position ${start:X} -> ${stop:X}, -${step:X} every {every} frames; ship held at the top")
    t0 = s.t
    n = (start - stop) // step + 1
    play(s, n * every, moves)
    s.ev(f"joy U {n * every}", t0)
    for i in range(n):
        p = start - i * step
        s.ev(f"poke ${POS:X} ${p:X}.w", t0 + i * every)
        s.ev(f"poke ${POS2:X} ${p:X}.w", t0 + i * every)
        s.ev(f"poke ${CLAMP:X} ${max(0, p - step):X}.w", t0 + i * every)
    s.ev(f"poke ${CLAMP:X} $0.w", t0 + n * every)
    s.pokes = True
    return s


def goto_level(s, level):
    """From a running level: set the level counter to level-1 and raise the level-complete flag: the main loop's own end-of-level
    path loads the requested level (side 1 tracks 0-13 are read)."""
    s.note(f"COVERAGE POKE: $E04={level - 1}, $A07=$FF -> the game's end-of-level path loads level {level}")
    s.poke(LEVEL, level - 1).poke(DONE, 0xFF, "b")
    s.ev("fire 6 every 50 until %d" % (s.t + 450))
    return s.wait(450)


def shop_request(s):
    s.note("COVERAGE POKE: $A6C=$FF -> shop request (the main loop runs the shop code; no disk read)")
    return s.poke(SHOPREQ, 0xFF, "b")


def shop(s, cells=4, step=30):
    """Shop (input ready ~500 frames after the request). Cursor: $4F2 column 0-4, $4F4 row 0-4, starting at (0,0); row 4 is the
    bottom bar where column 0 is EXIT. The shop opens in the SELL phase; EXIT there moves on to the BUY phase (cursor back to
    (0,0)); in the BUY phase a fire on a cell buys that item (one purchase per ~100 frames, the cash drops each time); EXIT in
    the BUY phase leaves. A direction is taken once it is held for about 12 frames."""
    if cells == 0:
        s.note("shop: leave at once (EXIT twice: SELL phase, then BUY phase)")
        s.poke(SHOP_COL, 0).poke(SHOP_ROW, 4)
        s.wait(20).fire(gap=250)
        s.poke(SHOP_COL, 0).poke(SHOP_ROW, 4)
        return s.wait(20).fire(gap=step)
    s.note("shop SELL phase: nothing to sell; COVERAGE POKE (UI only): cursor on EXIT ($4F2=0, $4F4=4), then fire")
    s.poke(SHOP_COL, 0).poke(SHOP_ROW, 4)
    s.wait(20).fire(gap=250)
    s.note(f"shop BUY phase: from (0,0) buy over {cells} cells (snake), a fire on each")
    row = col = 0
    for i in range(cells):
        s.fire(gap=70)
        s.fire(gap=110)
        if i + 1 == cells:
            break
        if (row % 2 == 0 and col < 4) or (row % 2 == 1 and col > 0):
            col += 1 if row % 2 == 0 else -1
            s.joy("R" if row % 2 == 0 else "L", gap=step)
        else:
            row += 1
            s.joy("D", gap=step)
    s.note("shop: COVERAGE POKE (UI only): cursor on EXIT in case a move was dropped, then fire")
    s.poke(SHOP_COL, 0).poke(SHOP_ROW, 4)
    return s.wait(20).fire(gap=step)


def shop_leave(s, tries=3, gap=100):
    """Leave the shop without buying: cursor on EXIT and fire, `tries` times `gap` frames apart (EXIT in the SELL phase moves on to
    the BUY phase, EXIT there leaves; a spare press after leaving only fires a shot)."""
    s.note(f"shop: leave without buying (cursor on EXIT $4F2=0/$4F4=4 and fire, {tries}x)")
    for _ in range(tries):
        s.poke(SHOP_COL, 0).poke(SHOP_ROW, 4)
        s.wait(20).fire(gap=gap)
    return s


def aim(s, right, left=80):
    s.note(f"aim: left {left} frames, then right {right} frames")
    s.ev(f"joy L {left}")
    s.wait(left)
    s.ev(f"joy R {right}")
    return s.wait(right)


def autofire(s, n):
    s.note(f"hold position, autofire for {n} frames")
    s.ev(f"joy F 2 every 4 until {s.t + n - 4}")
    return s.wait(n)


