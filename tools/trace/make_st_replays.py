"""Generate the Atari ST replay scripts tests/replays/st/*.txt and record their hash manifests (docs/re-notes/atari-st-replays.md).

The scripts are input scripts for `x2recomp --game st --input-script` (the project's format; every line is also expressible in the
Hatari harness's: see --hatari). Timings were measured against the interpreter runtime on the Kixx dump (sha1 323d6859...f3df994c)
with `--st-fdc-speed 8`; changing a script means re-recording its .hashes file.

    python3 tools/trace/make_st_replays.py [--out tests/replays/st] [NAME...]                      write the scripts
    python3 tools/trace/make_st_replays.py --record --exe build/x2recomp --disk kixx.st [NAME...]  write the manifests
    python3 tools/trace/make_st_replays.py --hatari NAME [--out-hatari DIR]                        a Hatari-format copy

The ST release has the disk build's engine variables at the same addresses (docs/re-notes/atari-st-hooks.md), so the coverage pokes
are the disk build's (tools/trace/make_replays.py):

  $E04.w level 1-5     $A07.b level-complete flag    $A6C.b shop request     $CD0/$CEA.w scroll position
  $CE8.w lower scroll clamp   $CD2/$CD4.w event cursors   $CC6.w energy (max $27)   $CCA.w ships   $CF0.w credits
  $C92.l score   $C9A.l cash   $4F2/$4F4.w shop cursor column/row   $B4C.l head of the hittable-object list   $428.w player index
  $D7A.w level-5 guardians left
Boss objects are found by their hit handler (+$A) on the list $B4C; the ST loads a level's code at $4F000, so the handlers differ
from the disk build's (the table is below, derived by type and HP and checked by behaviour: docs/re-notes/atari-st-replays.md).

Front end (frames, `--st-fdc-speed 8`): caption and title from ~1000, the first fire (at 1400) leaves the title, the SELECT menu is
up from ~1550 (1 PLAYER GAME / 2 PLAYER GAME / MUSIC), a fire at 1650 starts the game, level 1 is loaded at ~1760 and waits at GET READY
until a fire; the ship is controllable from ~2200. Directions are only taken when held for about 12 frames (the game polls the joystick
state once per logic step), so menu and shop moves hold 12.
"""
import argparse
