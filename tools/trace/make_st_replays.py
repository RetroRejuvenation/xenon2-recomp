def r_flood(n):
    s = Script(f"level{n}_flood", f"level {n}: one-step scroll jumps that fire each skipped stretch's events at once "
               "(many enemy types together)")
    front_end(s)
    invincible(s, 9500)
    s.wait(20)
    if n > 1:
        goto_level(s, n)
    play(s, 300)
    jumps = (0xC00, 0x900, 0x600, 0x300)
    each = (6400 - s.t) // len(jumps)
    for pos in jumps:
        flood_to(s, pos)
        play(s, each)
    return s.at(6400)


