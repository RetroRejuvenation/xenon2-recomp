#!/usr/bin/env python3
"""Generate the replay corpus tests/replays/*.txt (input scripts for x2recomp --input-script).

The scripts are plain text and committed; this generator documents how they were built and regenerates them.
Frame timings were measured against the interpreter runtime (screenshots and RAM peeks), so changing a script
means re-recording its .hashes file (tests/replays/README.md).

    python3 tools/trace/make_replays.py [--out tests/replays] [NAME...]

Game variables used by the coverage pokes (evidence in docs/re-notes/trace-coverage.md):
  $E04.w level 1-5     $A07.b level-complete flag    $A6C.b shop request     $CD0/$CEA/$CCE.w scroll position
  $CC6.w energy (max $27)  $CCA.w lives (ships)   $CF0.w credits (continues)  $C92.l score  $C9A.l cash
  $8FEC.b ending flag (set by the game itself when the level-5 shop is requested late in the level)
"""
import argparse
import os
import sys

KEY_P, KEY_ESC, KEY_SPACE = 0x19, 0x45, 0x40


class Script:
    def __init__(self, name, title):
        self.name = name
        self.lines = [f"# {name}: {title}", "# generated by tools/trace/make_replays.py"]
        self.t = 0
        self.pokes = False

    def at(self, t):
        self.t = t
        return self

    def wait(self, n):
        self.t += n
        return self

    def note(self, text):
        self.lines.append(f"# {text}")
        return self

    def ev(self, text, t=None):
        self.lines.append(f"{self.t if t is None else t} {text}")
        return self

    def fire(self, hold=3, gap=20):
        self.ev(f"fire {hold}")
        return self.wait(gap)

    def joy(self, dirs, hold=3, gap=20):
        self.ev(f"joy {dirs} {hold}")
        return self.wait(gap)

    def key(self, code, gap=20):
        self.ev(f"key {code:02x}")
        return self.wait(gap)

    def poke(self, addr, val, size="w", frames=1):
        self.pokes = True
        self.ev(f"poke ${addr:X} ${val:X}.{size}" + (f" {frames}" if frames != 1 else ""))
        return self

    def text(self):
        hdr = "# COVERAGE POKES ARE USED: game state is altered, not a faithful playthrough" if self.pokes else \
              "# no pokes: plain input only"
        return "\n".join(self.lines[:2] + [hdr] + self.lines[2:] + [f"frames {self.t}"]) + "\n"


# --- building blocks -------------------------------------------------------------------------------------

def start_game(s, players=1):
    """Title -> SELECT menu -> N PLAYER GAME -> loading level 1 -> GET READY; level 1 runs from ~frame 980."""
    s.note(f"title -> SELECT menu -> {players} PLAYER GAME -> GET READY")
    s.at(460).fire(5)
    s.at(620)
    if players == 2:
        s.joy("D")
    s.at(650).fire(5)
    s.ev("fire 5 every 50 until 900", 700)
    return s.at(980)


def play(s, n, moves="LRLRUDUD", seg=40):
    """Real play for n frames: fire tapped every 4 frames while sweeping the ship around."""
    if n < seg:
        return s.wait(max(0, n))
    s.note(f"play {n} frames: autofire taps while moving {moves}")
    end = s.t + n
    s.ev(f"joy F 2 every 4 until {end - 4}")
    i = 0
    while s.t + seg <= end:
        s.ev(f"joy {moves[i % len(moves)]} {seg - 6}")
        s.wait(seg)
        i += 1
    return s.at(end)


def invincible(s, frames):
    s.note(f"COVERAGE POKE: energy $CC6=$27 and lives $CCA=3 every frame for {frames} frames")
    s.poke(0xCC6, 0x27, frames=frames).poke(0xCCA, 3, frames=frames)
    return s


def flood_to(s, pos):
    """Jump the scroll position in one step without moving the event cursors: level_event_scan then fires every
    event of the skipped stretch at once, which spawns many enemy types together (more handler coverage, but it
    can exhaust the object pool; only used where it tested healthy)."""
    s.note(f"COVERAGE POKE: jump the scroll position ($CD0/$CEA, $CCE = 2.5x, clamp $CE8) to ${pos:X}; "
           "the skipped events all fire")
    s.poke(0xCD0, pos).poke(0xCEA, pos).poke(0xCCE, pos * 5 // 2)
    return s.poke(0xCE8, max(0, pos - 0x40))


def scroll_to(s, pos):
    """Jump the level scroll position. level_event_scan $3554 fires every event between the last scanned position
    ($CD2 for the list at $54E38, $CD4 for $54E14) and $CD0, so both are moved too: the skipped stretch's events
    are dropped instead of all spawning at once (that flood exhausts the object pool; in level 3 it ends in an
    endless obj_alloc loop on a self-linked list node)."""
    s.note(f"COVERAGE POKE: jump the scroll position ($CD0/$CEA/$CD2/$CD4, $CCE = 2.5x) to ${pos:X}")
    for a in (0xCD0, 0xCEA, 0xCD2, 0xCD4):
        s.poke(a, pos)
    return s.poke(0xCCE, pos * 5 // 2)


def fast_forward(s, start, stop, step=0x40, every=50, moves="LRLRUDUD"):
    """Advance the scroll position by `step` every `every` frames (natural speed is ~0.28/frame, so the default is
    ~4.5x) while playing. Only $CD0/$CEA/$CCE move: level_event_scan still fires every event passed, in order, a
    few at a time (one big jump fires them all at once and can exhaust the object pool). The lower scroll clamp
    $CE8 (a level's mid-boss scroll lock) is lowered just below each new position: a position under the clamp makes
    the scroll update ($7A0A) produce a huge delta, the background row $436 leaves 0-$BF and blit_objects_main
    ($17D6) then blits ~140 KB over the level module."""
    s.note(f"COVERAGE POKE: fast-forward the scroll position ${start:X} -> ${stop:X}, -${step:X} every {every} frames")
    t0, pos = s.t, start
    n = (start - stop) // step + 1
    play(s, n * every, moves)
    for i in range(n):
        p = start - i * step
        s.ev(f"poke $CD0 ${p:X}.w", t0 + i * every)
        s.ev(f"poke $CEA ${p:X}.w", t0 + i * every)
        s.ev(f"poke $CCE ${p * 5 // 2:X}.w", t0 + i * every)
        s.ev(f"poke $CE8 ${max(0, p - step):X}.w", t0 + i * every)
    s.pokes = True
    return s


def goto_level(s, level):
    """From a running level: set the level counter to level-1 and raise the level-complete flag. The main loop's
    own end-of-level path ($7C62 -> $7D0C addq $E04 -> $917E) then loads the requested level."""
    s.note(f"COVERAGE POKE: $E04={level - 1}, $A07=$FF -> the game's end-of-level path loads level {level}")
    s.poke(0xE04, level - 1).poke(0xA07, 0xFF, "b")
    s.ev("fire 5 every 50 until %d" % (s.t + 450))
    return s.wait(450)


def shop_request(s):
    s.note("COVERAGE POKE: $A6C=$FF -> shop request (main loop $7B8C -> $8FF2 loads disc-2 slot 6)")
    return s.poke(0xA6C, 0xFF, "b")


def shop(s, cells=20, step=18):
    """Shop (disc-2 slot 6); its input loop ($55F60) is ready ~470 frames after the request. Cursor: $4F2 column
    0-4, $4F4 row 0-4, starting at (0,0); row 4 is the bottom bar where column 0 is EXIT and any other column the
    SELL/BUY button; left/right there toggle between the two. Up/down wrap. A move blocks input for ~12 frames.
    The shop opens in the SELL phase; EXIT there moves on to the BUY phase (cursor back to (0,0)), where fire on a
    cell selects the item and a second fire on the same cell buys it ($55668); EXIT in the BUY phase leaves."""
    if cells == 0:
        s.note("shop: leave at once (EXIT twice: SELL phase, then BUY phase)")
        s.poke(0x4F2, 0).poke(0x4F4, 4)
        s.wait(30).fire(gap=90)
        s.poke(0x4F2, 0).poke(0x4F4, 4)
        return s.wait(30).fire(gap=step)
    s.note("shop SELL phase: fire on cells (0,0) and (0,1) (nothing to sell), the SELL button, then EXIT")
    s.fire(gap=40).joy("R", gap=step).fire(gap=40)
    for _ in range(4):
        s.joy("D", gap=step)
    s.fire(gap=40).joy("L", gap=step)
    s.note("COVERAGE POKE (UI only): cursor on EXIT ($4F2=0, $4F4=4) in case a move was dropped")
    s.poke(0x4F2, 0).poke(0x4F4, 4)
    s.wait(40).fire(gap=90)
    s.note(f"shop BUY phase: from (0,0) buy over {cells} cells (snake), select + buy on each")
    row = col = 0
    for i in range(cells):
        s.fire(gap=45).fire(gap=45)  # the shopkeeper's text prints before input is read again
        if i + 1 == cells:
            break
        if (row % 2 == 0 and col < 4) or (row % 2 == 1 and col > 0):
            col += 1 if row % 2 == 0 else -1
            s.joy("R" if row % 2 == 0 else "L", gap=step)
        else:
            row += 1
            s.joy("D", gap=step)
    s.note("shop: down to the bottom bar, EXIT")
    for _ in range(4 - row):
        s.joy("D", gap=step)
    if col != 0:
        s.joy("L", gap=step)
    s.note("COVERAGE POKE (UI only): cursor on EXIT in case a purchase dialog swallowed a move, then fire")
    s.wait(30).poke(0x4F2, 0).poke(0x4F4, 4)
    return s.wait(30).fire(gap=step)


# --- replays ---------------------------------------------------------------------------------------------

def r_attract():
    s = Script("attract", "no input: title, credits pages, high-score table (two attract cycles)")
    return s.at(5000)


def r_menu_2p():
    s = Script("menu_2p", "SELECT menu navigation, music toggle, 2-player game, pause, ESC to menu, 1-player restart")
    s.at(460).fire(5)
    s.at(640).note("menu: down to 2 PLAYER, down to MUSIC, fire x3 (off/on/off), down wraps, up x2")
    s.joy("D", gap=30).joy("D", gap=30)
    s.fire(gap=40).fire(gap=40).fire(gap=40)
    s.joy("D", gap=30).joy("U", gap=30).joy("U", gap=30)
    s.note("menu: on 2 PLAYER GAME (music off), start")
    s.fire(5, gap=40)
    s.ev("fire 5 every 50 until %d" % (s.t + 450))
    s.wait(450)
    play(s, 1200, "LURD")
    s.note("pause with P, hold still, unpause")
    s.key(KEY_P, gap=150).key(KEY_P, gap=60)
    play(s, 600, "RDLU")
    s.note("SPACE (main-loop key table entry $797A)")
    s.key(KEY_SPACE, gap=100)
    play(s, 400)
    s.note("ESC: quit to the SELECT menu ($7800)")
    s.key(KEY_ESC, gap=300)
    s.note("menu again: music back on, 1 PLAYER GAME")
    s.joy("D", gap=30).joy("D", gap=30).fire(gap=40).joy("U", gap=30).joy("U", gap=30)
    s.fire(5, gap=40)
    s.ev("fire 5 every 50 until %d" % (s.t + 450))
    s.wait(450)
    return play(s, 600)


def r_level1_play():
    s = Script("level1_play", "1-player level 1 with real movement and shooting, no pokes (deaths happen)")
    start_game(s)
    return play(s, 5000, "LLRRUUDDLRUD", seg=30)


def r_game_over():
    s = Script("game_over", "death, high-score entry, continue prompt (continue), last credit lost: GAME OVER")
    start_game(s)
    s.note("COVERAGE POKE: score $C92 = 2,000,000 (beats the table), one ship ($CCA=1), energy 1 so the next hit kills")
    s.poke(0xC92, 2000000, "l").poke(0xCCA, 1).poke(0xCC6, 1, frames=600)
    play(s, 600, "UD")
    s.note("high-score entry ($8A16): left/right choose a letter, fire accepts it (3 letters)")
    s.wait(300)
    for letters in ("RRRR", "LL", "R"):
        for d in letters:
            s.joy(d, gap=15)
        s.fire(gap=40)
    s.note("continue prompt ($8E88): fire to continue")
    s.wait(200).fire(gap=60).fire(gap=60)
    s.ev("fire 5 every 50 until %d" % (s.t + 400))
    s.wait(400)
    s.note("COVERAGE POKE: last credit ($CF0=1), one ship, energy 1; no input: the next death is GAME OVER ($7B4C)")
    s.poke(0xCF0, 1).poke(0xCCA, 1).poke(0xCC6, 1, frames=600)
    s.note("the small score still enters the table (the first entry shifted it): accept three letters")
    s.wait(700).fire(gap=40).fire(gap=40).fire(gap=40)
    return s.wait(900)


def r_shop():
    s = Script("shop", "level 1 mid-level shop reached by scrolling, buy all 20 items with poked cash, use them")
    start_game(s)
    invincible(s, 5000)
    s.note("COVERAGE POKE: cash $C9A = 200000")
    s.poke(0xC9A, 200000, "l")
    s.note("scroll just past level 1's shop trigger (level_frame $55806: $CD0+$3F040 < $A80)")
    scroll_to(s, 0x9E0)
    s.wait(520)
    shop(s)
    s.wait(450)
    return play(s, 6000 - s.t)


def r_shop5():
    s = Script("shop5", "level-5 shop (full stock, 'last chance' text): buy all 20 items with poked cash, then play")
    start_game(s)
    invincible(s, 5000)
    s.wait(20)
    goto_level(s, 5)
    play(s, 300)
    s.note("COVERAGE POKE: cash $C9A = 900000")
    s.poke(0xC9A, 900000, "l")
    shop_request(s)
    s.wait(600)
    shop(s)
    s.wait(450)
    return play(s, max(0, 6000 - s.t))


def r_level1_ff():
    s = Script("level1_ff", "level 1 fast-forwarded: first half, mid-level shop (exit at once), second half, boss")
    start_game(s)
    invincible(s, 5000)
    fast_forward(s, 0x1180, 0x9C0)
    s.wait(520 - 50)
    shop(s, cells=0)
    s.wait(450)
    fast_forward(s, 0x980, 0x40)
    return play(s, max(0, 6000 - s.t))


# Per level: where the scroll fast-forward stops.
LEVEL_PLANS = {
    2: dict(stop=0x40),
    3: dict(stop=0x40),
    4: dict(stop=0x40),
    5: dict(stop=0x600),  # level 5 moves the position back up itself around $560; going lower crashed (stray blit)
}


def r_level(n):
    plan = LEVEL_PLANS[n]
    s = Script(f"level{n}", f"level {n}: advanced from level 1, then the scroll position fast-forwarded to the end")
    start_game(s)
    invincible(s, 5600)
    s.wait(20)
    goto_level(s, n)
    play(s, 300)
    fast_forward(s, 0x1180, plan["stop"], every=50)
    return play(s, max(0, 6000 - s.t))


def r_flood(n):
    s = Script(f"level{n}_flood", f"level {n}: one-step scroll jumps that fire each skipped stretch's events at once "
               "(many enemy types together)")
    start_game(s)
    invincible(s, 5600)
    s.wait(20)
    if n > 1:
        goto_level(s, n)
    play(s, 300)
    jumps = (0xC00, 0x900, 0x600, 0x300, 0x100)
    each = (6000 - s.t) // len(jumps)
    for pos in jumps:
        flood_to(s, pos)
        play(s, each)
    return s.at(6000)


def r_ending():
    s = Script("ending", "level 5 late shop request: the game sets the ending flag $8FEC and slot 6 shows the ending")
    start_game(s)
    invincible(s, 5600)
    s.wait(20)
    goto_level(s, 5)
    play(s, 300)
    scroll_to(s, 0x200)
    s.wait(10)
    shop_request(s)
    s.ev("fire 3 every 200 until 5990", s.t + 400)
    return s.at(6000)


REPLAYS = {
    "attract": r_attract,
    "menu_2p": r_menu_2p,
    "level1_play": r_level1_play,
    "level1_ff": r_level1_ff,
    "game_over": r_game_over,
    "shop": r_shop,
    "shop5": r_shop5,
    "level2": lambda: r_level(2),
    "level3": lambda: r_level(3),
    "level4": lambda: r_level(4),
    "level5": lambda: r_level(5),
    "ending": r_ending,
    # Level 3 is left out: the flood hangs it in obj_alloc (self-linked node in list $B4C), and level 5 adds nothing.
    "level1_flood": lambda: r_flood(1),
    "level2_flood": lambda: r_flood(2),
    "level4_flood": lambda: r_flood(4),
}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "..", "tests", "replays"))
    ap.add_argument("names", nargs="*")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    for name in a.names or REPLAYS:
        s = REPLAYS[name]()
        with open(os.path.join(a.out, name + ".txt"), "w") as f:
            f.write(s.text())
        print(f"{name}: {s.t} frames{' (pokes)' if s.pokes else ''}", file=sys.stderr)


if __name__ == "__main__":
    main()
